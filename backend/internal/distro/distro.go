// points lists major.hi down to major.lo, the point-release tags a vendor keeps.
func points(prefix string, major, hi, lo int, group string) []Release {
	rs := make([]Release, 0, hi-lo+1)
	for m := hi; m >= lo; m-- {
		v := fmt.Sprintf("%d.%d", major, m)
		rs = append(rs, Release{Version: v, Name: prefix + v, Group: group})
	}
	return rs
}

func concat(groups ...[]Release) []Release {
	var out []Release
	for _, g := range groups {
		out = append(out, g...)
	}
	return out
}

