// Package names across apt and dnf: letters, digits and the punctuation both
// package managers use for arch/version suffixes. No shell metacharacters, no
// spaces, and no leading dash, so nothing can turn into a flag or a second command.
var pkgRe = regexp.MustCompile(`^[A-Za-z0-9][A-Za-z0-9+._:=~-]*$`)

func ValidPackages(pkgs []string) error {
	if len(pkgs) == 0 {
		return fmt.Errorf("no packages given")
	}
	for _, p := range pkgs {
		if !pkgRe.MatchString(p) {
			return fmt.Errorf("bad package name: %q", p)
		}
	}
	return nil
}

// Search terms are looser than package names — a prefix is the normal case — but
// they still land in a shell command, so the same "no metacharacters" rule applies.
var termRe = regexp.MustCompile(`^[A-Za-z0-9][A-Za-z0-9+._-]{0,63}$`)

func ValidTerm(q string) error {
	if !termRe.MatchString(q) {
		return fmt.Errorf("bad search term: %q", q)
	}
	return nil
}

type Package struct {
	Name     string   `json:"name"`
	Summary  string   `json:"summary"`
	Versions []string `json:"versions,omitempty"` // newest first, as the repositories list them
}

// archRe strips the .x86_64 dnf appends to every name it prints.
var archRe = regexp.MustCompile(`\.(x86_64|noarch|i686|aarch64|src)$`)

// versionRe is one "name | version | source" line: apt-cache madison, and the
// same shape the dnf search script prints.
var versionRe = regexp.MustCompile(`^\s*(\S+) \| (\S+) \| (.*)$`)

// ParseSearch reads the two shapes the package managers print:
// apt "name - summary" and dnf "name.arch : summary", plus the version lines.
func ParseSearch(out string) []Package {
	var pkgs []Package
	seen := map[string]bool{}
	versions := map[string][]string{}
	for _, line := range strings.Split(out, "\n") {
		if m := versionRe.FindStringSubmatch(line); m != nil {
			// Source packages are not something a bundle can install.
			if !strings.HasSuffix(strings.TrimSpace(m[3]), "Sources") && !slices.Contains(versions[m[1]], m[2]) {
				versions[m[1]] = append(versions[m[1]], m[2])
			}
			continue
		}
		name, summary, ok := strings.Cut(line, " : ")
		if !ok {
			if name, summary, ok = strings.Cut(line, " - "); !ok {
				continue
			}
		}
		name = archRe.ReplaceAllString(strings.TrimSpace(name), "")
		if name == "" || seen[name] || !pkgRe.MatchString(name) {
			continue
		}
		seen[name] = true
		pkgs = append(pkgs, Package{Name: name, Summary: strings.TrimSpace(summary)})
	}
	for i := range pkgs {
		pkgs[i].Versions = versions[pkgs[i].Name]
	}
	sort.Slice(pkgs, func(i, j int) bool { return len(pkgs[i].Name) < len(pkgs[j].Name) })
	return pkgs
}

// notFoundRe covers what apt, dnf and yum say when a name is not in the repos.
var notFoundRe = regexp.MustCompile(`(?m)Package '([^']+)' has no installation candidate` +
	`|Unable to locate package (\S+)` +
	`|No match for argument:? (\S+)` +
	`|No package (\S+) available`)

// NotFound pulls the package names the package manager rejected out of a build
// log, so a failed job can say which name was wrong instead of "exit status 100".
func NotFound(log string) []string {
	seen := map[string]bool{}
	var out []string
	for _, m := range notFoundRe.FindAllStringSubmatch(log, -1) {
		for _, g := range m[1:] {
			if g != "" && !seen[g] {
				seen[g] = true
				out = append(out, g)
			}
		}
	}
	sort.Strings(out)
	return out
}

// ponytail: apt skips deps already present in the base image, which matches a
// stock Ubuntu target. For a stripped target, name those packages explicitly.
const aptScript = `set -e
PKGS="{{PKGS}}"
mkdir -p /out/partial
# EOL releases leave the mirrors: Ubuntu moves to old-releases, Debian to
# archive.debian.org, whose Release files are expired by design.
apt-get update || {
  sed -i -e "s|archive.ubuntu.com|old-releases.ubuntu.com|g" -e "s|security.ubuntu.com|old-releases.ubuntu.com|g" -e "s|deb.debian.org|archive.debian.org|g" -e "s|security.debian.org|archive.debian.org|g" /etc/apt/sources.list /etc/apt/sources.list.d/* 2>/dev/null || true
  apt-get -o Acquire::Check-Valid-Until=false update
}
# Enabling an extra repository needs curl and gnupg, and installing those puts
# their dependencies (ca-certificates, libssl3, ...) into this image. apt would
# then skip them as "already installed" and the bundle would be missing exactly
# the packages the target does not have. Resolve against the image as it was.
cp /var/lib/dpkg/status /tmp/packark-status.pre
{{REPOS}}
apt-get install -y --download-only --reinstall -o Dir::State::status=/tmp/packark-status.pre -o Dir::Cache::archives=/out $PKGS
rm -rf /out/partial /out/lock
apt-get install -y apt-utils
(cd /out && apt-ftparchive packages . > Packages && apt-ftparchive release . > Release)
cat > /out/install.sh <<SH
#!/bin/sh
# Offline install: the bundle is a flat apt repository, and only the packages
# that were asked for are installed from it. Feeding every .deb to dpkg would
# install the whole bundle, whether the machine needs it or not.
set -e
cd "\$(dirname "\$0")"
if [ "\$(id -u)" -ne 0 ]; then
  echo "run this as root: sudo ./install.sh" >&2
  exit 1
fi
# A private sources list and lists dir: apt sees only the bundle, and the
# machine's own apt state is left untouched.
TMP=\$(mktemp -d)
trap 'rm -rf "\$TMP"' EXIT INT TERM
mkdir -p "\$TMP/parts" "\$TMP/lists/partial"
echo "deb [trusted=yes] file:\$PWD ./" > "\$TMP/sources.list"
APT="-o Dir::Etc::SourceList=\$TMP/sources.list -o Dir::Etc::SourceParts=\$TMP/parts -o Dir::State::Lists=\$TMP/lists -o Dir::Cache::pkgcache= -o Dir::Cache::srcpkgcache="
apt-get \$APT update
apt-get \$APT install -y $PKGS
SH
chmod +x /out/install.sh
tar czf /bundle.tar.gz -C /out .
`

// --alldeps pulls the whole dependency tree, including packages the base image
// already has, so the bundle stands on its own. Oracle Linux 7 predates dnf.
const dnfScript = `set -e
PKGS="{{PKGS}}"
mkdir -p /out
{{REPOS}}
if command -v dnf >/dev/null 2>&1; then
  dnf install -y dnf-plugins-core || dnf install -y dnf5-plugins
  dnf download --resolve --alldeps --destdir /out $PKGS
  dnf install -y createrepo_c
  createrepo_c --quiet /out
else
  yum install -y yum-utils createrepo
  yumdownloader --resolve --destdir /out $PKGS
  createrepo --quiet /out
fi
cat > /out/install.sh <<SH
#!/bin/sh
# Offline install: the bundle is a yum repository, and only the packages that
# were asked for are installed from it. Handing the package manager every rpm
# instead (dnf install ./*.rpm) makes it reconcile the whole dependency tree
# against what is already on the machine, and it resolves that by erasing
# protected packages — "would result in removing: systemd".
set -e
cd "\$(dirname "\$0")"
if [ "\$(id -u)" -ne 0 ]; then
  echo "run this as root: sudo ./install.sh" >&2
  exit 1
fi
REPO=/etc/yum.repos.d/packark-local.repo
cat > "\$REPO" <<EOF
[packark-local]
name=packark offline bundle
baseurl=file://\$PWD
enabled=1
gpgcheck=0
# Modular packages (container-selinux, fuse-overlayfs, …) carry a module tag but
# the bundle has no module metadata, so dnf would refuse them. This says to treat
# everything here as plain rpms, which is what a bundle is.
module_hotfixes=1
EOF
trap 'rm -f "\$REPO"' EXIT INT TERM
if command -v dnf >/dev/null 2>&1; then
  dnf install -y --disablerepo='*' --enablerepo=packark-local $PKGS
else
  yum install -y --disablerepo='*' --enablerepo=packark-local $PKGS
fi
SH
chmod +x /out/install.sh
tar czf /bundle.tar.gz -C /out .
`

// aptSearch runs in the target image so the hit list is exactly what that
// release ships. Same old-releases fallback as the download script.
const aptSearch = `set -e
{
echo "reading the package lists for this release..."
apt-get update || {
  echo "the mirrors moved: retrying against the archive"
  sed -i -e "s|archive.ubuntu.com|old-releases.ubuntu.com|g" -e "s|security.ubuntu.com|old-releases.ubuntu.com|g" -e "s|deb.debian.org|archive.debian.org|g" -e "s|security.debian.org|archive.debian.org|g" /etc/apt/sources.list /etc/apt/sources.list.d/* 2>/dev/null || true
  apt-get -o Acquire::Check-Valid-Until=false update
}
{{REPOS}}
echo "searching..."
} >&2
apt-cache search --names-only "{{TERM}}" | head -200 > /tmp/hits
cat /tmp/hits
# Every version each hit can be pinned to, newest first: "name | version | source".
cut -d' ' -f1 /tmp/hits | xargs -r apt-cache madison 2>/dev/null || true
`

// dnfSearch prints "name.arch : summary" lines; the header lines have no " : ".
const dnfSearch = `set -e
{
:
{{REPOS}}
echo "searching..."
} >&2
#
# Then every version of each hit, as "name | version | repo" lines like apt's
# madison prints, newest first.
if command -v dnf >/dev/null 2>&1; then
  dnf -q search "{{TERM}}" 2>/dev/null | grep " : " | head -200 > /tmp/hits || true
  cat /tmp/hits
  sed 's/\.[^.]* : .*//' /tmp/hits | sort -u |
    xargs -r dnf -q repoquery --qf '%{name} | %{evr} | %{repoid}\n' 2>/dev/null | sort -rV || true
else
  yum -q search "{{TERM}}" 2>/dev/null | grep " : " | head -200 > /tmp/hits || true
  cat /tmp/hits
  # ponytail: yum wraps rows whose name is too long; those versions are skipped.
  sed 's/\.[^.]* : .*//' /tmp/hits | sort -u |
    xargs -r yum -q list --showduplicates available 2>/dev/null |
    awk 'NF == 3 && $1 ~ /\./ { sub(/\.[^.]*$/, "", $1); print $1 " | " $2 " | " $3 }' | sort -rV || true
fi
`
