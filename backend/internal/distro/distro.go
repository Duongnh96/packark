// Package distro holds the supported distributions, their release whitelists,
// and the in-container script that downloads packages for each.
package distro

import (
	"fmt"
	"regexp"
	"slices"
	"sort"
	"strings"
)

type Release struct {
	Version string `json:"version"`
	Name    string `json:"name"`
	Group   string `json:"group"` // optgroup label in the picker
	Tag     string `json:"-"`     // image tag, when it differs from Version
}

// ImageTag is the docker tag for this release.
func (r Release) ImageTag() string {
	if r.Tag != "" {
		return r.Tag
	}
	return r.Version
}

type Distro struct {
	ID       string    `json:"id"`
	Name     string    `json:"name"`
	Image    string    `json:"-"` // docker image; the release supplies the tag
	Releases []Release `json:"releases"`
	Script   string    `json:"-"` // build script; {{PKGS}} and {{REPOS}} are filled in
	Search   string    `json:"-"` // search script; {{TERM}} and {{REPOS}} are filled in
	CacheDir string    `json:"-"` // package manager metadata, kept in a docker volume between searches

	// RepoFamily is "apt" or "dnf": which shape an extra repository takes.
	RepoFamily string `json:"repo_family"`
	// TagRe is which registry tags count as releases for this image.
	TagRe   *regexp.Regexp `json:"-"`
	Presets []RepoPreset   `json:"presets,omitempty"`
	Note    string         `json:"note,omitempty"`
}

// render fills a script's placeholders. Everything substituted here is either
// generated by packark or has been through the validators in this package.
func render(script string, fields map[string]string) string {
	for k, v := range fields {
		script = strings.ReplaceAll(script, "{{"+k+"}}", v)
	}
	return script
}

// BuildScript is the shell that downloads pkgs, with repos enabled first.
func (d Distro) BuildScript(pkgs []string, repos []Repo) string {
	return render(d.Script, map[string]string{
		"PKGS":  strings.Join(pkgs, " "),
		"REPOS": RepoSetup(d, repos),
	})
}

// SearchScript looks for term in the same repositories a build would use.
func (d Distro) SearchScript(term string, repos []Repo) string {
	return render(d.Search, map[string]string{
		"TERM":  term,
		"REPOS": RepoSetup(d, repos),
	})
}

func (d Distro) HasVersion(v string) bool {
	_, ok := d.Release(v)
	return ok
}

func (d Distro) Release(v string) (Release, bool) {
	for _, r := range d.Releases {
		if r.Version == v {
			return r, true
		}
	}
	return Release{}, false
}

// ImageRef is the image:tag the build runs in; empty for an unknown release.
func (d Distro) ImageRef(version string) string {
	r, ok := d.Release(version)
	if !ok {
		return ""
	}
	return d.Image + ":" + r.ImageTag()
}

